fn translate_golden(isa: Isa, path: &str) -> String {
    let src = std::fs::read_to_string(path).unwrap();
    let r = wrench::with_arch!(isa, A, {
        catch(|| translate::<A>(1000, &[0; 1000], path, &src)).map(|tr| {
            let width = hex_addr_width(tr.dump.size);
            let show = |a: i64| hex_addr(width, a);
            format!(
                "{}\n---\n{}\n---\n",
                pretty_labels(&show, &tr.labels),
                pretty_dump(true, &show, &tr.labels, &tr.dump.cells())
            )
        })
    });
    r.unwrap_or_else(|e| format!("Translation failed: {}", e))
}

fn simulate_golden(isa: Isa, path: &str, conf_path: &str, should_fail: bool) -> (String, Option<String>) {
    let src = std::fs::read_to_string(path).unwrap();
    let conf = Config::read(conf_path).unwrap();
    let opts = Options {
        input: path.to_string(),
        ..Options::default()
    };
    wrench::with_arch!(isa, A, {
        match catch(|| wrench::<A>(&opts, &conf, &src)) {
            Ok(r) => {
                let text: String = r
                    .warnings
                    .iter()
                    .map(|w| format!("warning: {}\n", w))
                    .collect::<String>()
                    + &r.trace;
                let problem =
                    (r.success == should_fail).then(|| format!("success = {}, expected {}", r.success, !should_fail));
                (text, problem)
            }
            Err(e) => (
                format!("error: {}", e),
                Some("simulation returned an error".to_string()),
            ),
        }
    })
}

fn isa_ext(isa: Isa) -> &'static str {
    isa.name()
}

fn first_diff(a: &str, b: &str) -> String {
    for (k, (x, y)) in a.lines().zip(b.lines()).enumerate() {
        if x != y {
            return format!("line {}:\n  expected: {:?}\n  actual:   {:?}", k + 1, x, y);
        }
    }
    format!(
        "length differs: expected {} lines, actual {} lines",
        a.lines().count(),
        b.lines().count()
    )
}

